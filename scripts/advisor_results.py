def require(ok,message):
    if not ok:raise ValueError(message)

def coverage(rows,expected,label):
    ids=[s for r in rows for s in r.get('source_ids',[])]
    actual=Counter(ids);wanted=Counter(list(expected))
    require(actual==wanted,label+' coverage missing/duplicate/unsupplied: missing='+str(sorted((wanted-actual).elements()))+'; extra='+str(sorted((actual-wanted).elements())))
    require(all(r.get('source_ids') for r in rows),label+' empty group')

def nonempty_text(value):
    return isinstance(value,str) and bool(value.strip())

def dependencies_valid(value):
    return nonempty_text(value) or (isinstance(value,list) and bool(value) and all(nonempty_text(v) for v in value))

def expand(raw,context):
    require(context.get('advisor_shared_results')==1,'Shared results not enabled')
    require(not set(raw)&{'relations','checks','findings','card_dispositions','writing_transfers','source_use_dispositions'},'Mixed shared and legacy result lists')
    require(set(raw)<={'stage','analyses','concern_results','expression_results','adopted_uses','association_exceptions','evidence_requests','limits'},'Unexpected shared result field')
    primary=context['primary_card_ids'];sources={r['id']:r for r in context['expression_sources']['records']}
    supplied={c['id'] for c in context['cards']}
    returned={s for row in raw['concern_results'] for s in row.get('source_ids',[])}
    coverage(raw['concern_results'],set(primary)|(returned & (supplied-set(primary))),'Concern')
    coverage(raw['expression_results'],sources,'Expression')
    analyses=raw['analyses'];byid={a['id']:a for a in analyses}
    require(len(byid)==len(analyses),'Duplicate analysis ID')
    stage=raw['stage']
    # Packet contexts do not always carry stage; caller pins it during expansion.
    require(isinstance(stage,str) and stage.startswith('supplement_'),'Missing shared-result stage')
    mapped={aid:{'r':f'{stage}:R{i}','c':f'{stage}:C{i}','f':f'{stage}:F{i}','g':f'{stage}:G{i}'} for i,aid in enumerate(byid,1)}
    cards={aid:set() for aid in byid}
    dispositions=[];context_dispositions=[]
    for row in raw['concern_results']:
        state=row['state'];links=row['analysis_ids']
        require(state in {'linked','sufficient','not_applicable','unknown','unfinished'},'Invalid Concern state')
        require(isinstance(row['reason'],str) and row['reason'].strip(),'Missing Concern reason')
        require(len(links)==len(set(links)) and set(links)<=set(byid),'Unknown/duplicate Concern analysis')
        require(bool(links)==(state=='linked'),'Concern linked state/analyses mismatch')
        for cid in row['source_ids']:
            for aid in links:cards[aid].add(cid)
            destination=dispositions if cid in primary else context_dispositions
            destination.append({'card_id':cid,'state':state,'reason':row['reason'],'relation_ids':[mapped[a]['r'] for a in links],'writing_scope':'shared_analysis'})
    transfers=[];expression_rows=[]
    for row in raw['expression_results']:
        if 'actions' in row:
            require(set(row)=={'source_ids','actions'} and len(row['source_ids'])==1 and row['actions'],'Invalid multiple-action source result')
            for action in row['actions']:
                require('source_ids' not in action and action.get('decision') in {'required_repair','optional_improvement'},'Invalid nested action')
                expression_rows.append({**action,'source_ids':row['source_ids']})
        else:expression_rows.append(row)
    for row in expression_rows:
        decision=row['decision']
        if decision in {'keep','not_applicable','unknown','unfinished'}:
            require(not row.get('analysis_ids') and not row.get('supporting_concern_ids'),'Non-action row cannot claim adoption')
            for sid in row['source_ids']:
                transfers.append({'id':f'{stage}:W{len(transfers)+1}','source_kind':'mentor_expression','source_id':sid,'assessment':'brief','decision':decision,'reason':row['reason'],'target_anchors':copy.deepcopy(row.get('target_anchors',[]))})
            continue
        require(decision in {'required_repair','optional_improvement'} and len(row['source_ids'])==1,'Invalid/grouped actionable Expression')
        sid=row['source_ids'][0];links=row['analysis_ids']
        require(links and len(links)==len(set(links)) and set(links)<=set(byid),'Unknown/empty Expression analysis')
        supporting=row['supporting_concern_ids']
        require(set(supporting)<={c['id'] for c in context['cards']},'Unknown supporting Concern')
        for cid in set(supporting)&set(primary):
            disposition=next(d for d in raw['concern_results'] if cid in d['source_ids'])
            require(disposition['state']=='linked' and set(links)<=set(disposition['analysis_ids']), 'Expression support contradicts primary Concern result')
        for aid in links:cards[aid].update(supporting)
        aa=[byid[a] for a in links]
        output_key='finding' if decision=='required_repair' else 'suggestion'
        require(all(a.get(output_key) for a in aa),'Expression action lacks explicit matching output')
        join=lambda key:'\n'.join(a[key] for a in aa)
        transfers.append({'id':f'{stage}:W{len(transfers)+1}','source_kind':'mentor_expression','source_id':sid,
          'decision':decision,'source_excerpt':row['source_excerpt'],'expression_excerpt_basis':row['expression_excerpt_basis'],
          'scope':row['scope'],'learned_distinction':row['contribution'],'reader_task':join('passage_job'),
          'current_handling':join('author_explanation'),'proposed_action':'\n'.join(a[output_key]['closure_goal' if output_key=='finding' else 'proposed_order'] for a in aa),
          'preserved_dependencies':row['preserved_dependencies'],'limits':row['limits'],
          'target_anchors':[copy.deepcopy(a['anchor']) for a in aa],'check_ids':[mapped[a]['c'] for a in links],
          'finding_ids':[mapped[a]['f'] for a in links] if output_key=='finding' else [],
          'suggestion_ids':[mapped[a]['g'] for a in links] if output_key=='suggestion' else [],
          'expression_contribution':{'role':row['role'],'feature_ids':row['feature_ids'],'supporting_concern_ids':supporting}})
    result={'relations':[],'checks':[],'findings':[],'organization_suggestions':[],
      'card_dispositions':dispositions,'context_card_dispositions':context_dispositions,'writing_transfers':transfers,'evidence_requests':raw.get('evidence_requests',[]),'limits':raw.get('limits',[])}
    result['analysis_id_map']=[{'analysis_id':a['id'],'relation_id':mapped[a['id']]['r'],'check_id':mapped[a['id']]['c'],
      'finding_id':mapped[a['id']]['f'] if a.get('finding') else None,'suggestion_id':mapped[a['id']]['g'] if a.get('suggestion') else None} for a in analyses]
    for a in analyses:
        ident=mapped[a['id']];finding=a.get('finding');suggestion=a.get('suggestion')
        require(a['id'].startswith(stage+':A'),'Analysis namespace')
        require(bool(finding)==(a['execution']=='completed' and a['judgment']=='gap'),'Gap/finding mismatch')
        require(not suggestion or (a['execution']=='completed' and a['judgment']=='sufficient'),'Optional suggestion needs sufficient baseline')
        result['relations'].append({'id':ident['r'],'anchor':a['anchor'],'relation':a['relation'],'passage_job':a['passage_job']})
        result['checks'].append({**{k:a[k] for k in ['anchor','execution','judgment','author_explanation','counterevidence','reason','local_support','later_support']},'id':ident['c'],'relation_id':ident['r'],'card_ids':sorted(cards[a['id']]),'finding_ids':[ident['f']] if finding else []})
        if finding:result['findings'].append({**finding,'id':ident['f'],'relation_id':ident['r'],'anchor':a['anchor'],'relation':a['relation'],'check_ids':[ident['c']]})
        if suggestion:result['organization_suggestions'].append({**suggestion,'id':ident['g'],'anchor':a['anchor'],'check_ids':[ident['c']]})
        if suggestion and not any(ident['g'] in t.get('suggestion_ids',[]) for t in transfers):
            # A manuscript-driven optional proposal is explicit in the analysis;
            # this adapter supplies only the existing downstream record shape.
            transfers.append({'id':f'{stage}:W{len(transfers)+1}','source_kind':'manuscript','source_id':'manuscript',
              'source_excerpt':'','scope':suggestion['scope'],'decision':'optional_improvement',
              'learned_distinction':suggestion['reason'],'reader_task':a['passage_job'],
              'current_handling':suggestion['current_order'],'proposed_action':suggestion['proposed_order'],
              'preserved_dependencies':suggestion['affected_links'],'limits':suggestion['conditions'],
              'target_anchors':[a['anchor']],'check_ids':[ident['c']],'finding_ids':[],'suggestion_ids':[ident['g']]})
    uses=context['source_uses'];explicit={}
    for row in raw.get('adopted_uses',[]):
        i=row['use_id'];require(type(i)is int and 1<=i<=len(uses) and i not in explicit,'Unknown/duplicate adopted use')
        u=uses[i-1];require(row['expression_id']==u['expression_id'],'Adopted source mismatch')
        ts=[t for t in transfers if t['source_id']==u['expression_id'] and t['decision'] in {'required_repair','optional_improvement'} and u['target_id'] in t['expression_contribution']['supporting_concern_ids']]
        require(u['target_kind']=='concern' and ts,'Adopted association lacks actual supported action')
        explicit[i]={'status':'adopted','reason':row['reason'],'transfer_ids':[t['id'] for t in ts]}
    for row in raw.get('association_exceptions',[]):
        i=row['use_id'];require(type(i)is int and 1<=i<=len(uses) and i not in explicit,'Unknown/duplicate exception use')
        require(row['status'] in {'conflict','uncertain'},'Invalid association exception')
        explicit[i]={'status':row['status'],'reason':row['reason'],'transfer_ids':[]}
    result['source_use_dispositions']=[{**{k:u[k] for k in ['expression_id','target_kind','target_id']},**explicit.get(i,{'status':'not_assessed','reason':'No association judgment was returned; candidate preserved, not reviewed.','transfer_ids':[]})} for i,u in enumerate(uses,1)]
    result['expression_result_manifest']=[{'source_id':sid,'transfer_ids':[t['id'] for t in transfers if t['source_kind']=='mentor_expression' and t['source_id']==sid]} for sid in sources]
    result['source_review_summary']=summary(result)
    return result

def summary(result):
    return {'concern_states':dict(Counter(r['state'] for r in result['card_dispositions'])),
      'context_concern_states':dict(Counter(r['state'] for r in result.get('context_card_dispositions',[]))),
      'expression_states':dict(Counter('/'.join(sorted({t['decision'] for t in result['writing_transfers'] if t['id'] in r['transfer_ids']})) for r in result['expression_result_manifest'])),
      'association_states':dict(Counter(r['status'] for r in result['source_use_dispositions'])),
      'analysis_states':dict(Counter('unfinished' if r['execution']=='unfinished' else r['judgment'] for r in result['checks'])),
      'scope':'Explicit per-source decisions; unknown/unfinished are unresolved. Unlisted associations are not_assessed, never checked.'}

def validate_uses(response,context):
    require(Counter(r['card_id'] for r in response['card_dispositions'])==Counter(context['primary_card_ids']),'Concern coverage missing/duplicate/unsupplied')
    contextual=response.get('context_card_dispositions',[])
    available={c['id'] for c in context['cards']}-set(context['primary_card_ids'])
    require(len({r['card_id'] for r in contextual})==len(contextual) and {r['card_id'] for r in contextual}<=available,'Invalid/duplicate context Concern')
    checks=response['checks'];relations={c.get('relation_id',c.get('object_id')) for c in checks}
    for row in contextual:
        require(row['state'] in {'linked','sufficient','not_applicable','unknown','unfinished'} and nonempty_text(row['reason']),'Invalid context Concern judgment')
        require(len(row['relation_ids'])==len(set(row['relation_ids'])) and set(row['relation_ids'])<=relations,'Invalid context Concern analysis links')
        require(bool(row['relation_ids'])==(row['state']=='linked'),'Context Concern state/links mismatch')
        if row['state']=='linked':require(all(any(c.get('relation_id',c.get('object_id'))==rid and row['card_id'] in c['card_ids'] for c in checks) for rid in row['relation_ids']),'Context Concern lacks linked evidence')
    manifest=response['expression_result_manifest'];transfers={t['id']:t for t in response['writing_transfers']}
    require(Counter(r['source_id'] for r in manifest)==Counter(r['id'] for r in context['expression_sources']['records']),'Expression coverage missing/duplicate/unsupplied')
    require(Counter(tid for r in manifest for tid in r['transfer_ids'])==Counter(t['id'] for t in response['writing_transfers'] if t['source_kind']=='mentor_expression'),'Expression result binding missing/duplicate')
    for row in manifest:
        require(row['transfer_ids'] and all(t in transfers and transfers[t]['source_id']==row['source_id'] for t in row['transfer_ids']),'Expression result references another source')
    expected=Counter((u['expression_id'],u['target_kind'],u['target_id']) for u in context['source_uses'])
    rows=response['source_use_dispositions']
    require(Counter((u['expression_id'],u['target_kind'],u['target_id']) for u in rows)==expected,'Association manifest coverage mismatch')
    ts={t['id']:t for t in response['writing_transfers']}
    for row in rows:
        require(row['status'] in {'adopted','not_assessed','conflict','uncertain'},'Invalid association status')
        require(isinstance(row['reason'],str) and row['reason'].strip(),'Missing association reason')
        links=row['transfer_ids'];require(isinstance(links,list) and len(links)==len(set(links)),'Invalid association links')
        if row['status']=='adopted':
            require(links and all(t in ts and ts[t]['source_id']==row['expression_id'] and ts[t]['decision'] in {'required_repair','optional_improvement'} and row['target_id'] in ts[t]['expression_contribution']['supporting_concern_ids'] for t in links),'Unsupported association adoption')
        else:require(not links,'Non-adopted association claims action')
    require(response.get('source_review_summary')==summary(response),'Source review summary mismatch')
